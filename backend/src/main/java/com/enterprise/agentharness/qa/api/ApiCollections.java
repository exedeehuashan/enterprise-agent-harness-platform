package com.enterprise.agentharness.qa.api;

import com.fasterxml.jackson.core.JsonParser;
import com.fasterxml.jackson.databind.DeserializationFeature;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Set;

/**
 * Parses a project's API test file ({@code .eahp/api-tests.json}): declarative HTTP test cases that EAHP runs against
 * a registered environment. The file comes from the repository and is untrusted: every field is checked, unknown
 * fields are rejected and sizes are bounded. It only chooses services by name and paths; the hosts come from the
 * environment an approver registered. The format is meant to be written by people and, later, generated by a model.
 *
 * <pre>{"schemaVersion":1,"collections":[{"key":"order-api-smoke","name":"Order API smoke","service":"order-api",
 *   "variables":{"customerId":"eahp-{{$runId}}"},
 *   "cases":[{"id":"TC-001","name":"Create an order","steps":[{"name":"create",
 *     "request":{"method":"POST","path":"/api/v1/customers/{{customerId}}/orders","headers":{"Idempotency-Key":"{{$uuid}}"},"json":{...}},
 *     "expect":{"status":201,"headers":{"Location":{"exists":true}},"json":[{"path":"$.status","equals":"DRAFT"}],"maxMillis":2000},
 *     "capture":{"orderId":"$.id","etag":"header:ETag"}}]}]}]}</pre>
 */
public final class ApiCollections {
    public static final String FILE = ".eahp/api-tests.json";
    public static final int MAX_BYTES = 256 * 1024;
    static final Set<String> METHODS = Set.of("GET", "POST", "PUT", "PATCH", "DELETE", "HEAD");
    private static final ObjectMapper STRICT = new ObjectMapper()
            .enable(JsonParser.Feature.STRICT_DUPLICATE_DETECTION).enable(DeserializationFeature.FAIL_ON_TRAILING_TOKENS);

    private ApiCollections() {}

    /** Returns the collections, each as validated JSON (stored verbatim in the run, so approvals bind it). */
    public static List<JsonNode> parse(String json) {
        JsonNode root;
        try { root = STRICT.readTree(json); } catch (Exception ex) { throw invalid("not valid JSON"); }
        fields(root, Set.of("schemaVersion", "collections"), "file");
        if (!root.path("schemaVersion").isInt() || root.get("schemaVersion").intValue() != 1) throw invalid("schemaVersion must be 1");
        var collections = root.get("collections");
        if (collections == null || !collections.isArray() || collections.isEmpty() || collections.size() > 20) throw invalid("collections must list 1..20 collections");
        Set<String> keys = new HashSet<>();
        List<JsonNode> result = new ArrayList<>();
        for (JsonNode c : collections) {
            fields(c, Set.of("key", "name", "description", "service", "variables", "cases"), "collection");
            String key = text(c, "key", 60, true);
            if (!key.matches("[a-z0-9][a-z0-9-]{1,59}") || !keys.add(key)) throw invalid("collection key '" + key + "' is invalid or repeated");
            text(c, "name", 120, true);
            text(c, "description", 1000, false);
            service(c, true, key);
            variables(c.get("variables"), key);
            var cases = c.get("cases");
            if (cases == null || !cases.isArray() || cases.isEmpty() || cases.size() > 200) throw invalid(key + ": cases must list 1..200 cases");
            Set<String> ids = new HashSet<>();
            for (JsonNode tc : cases) {
                fields(tc, Set.of("id", "name", "service", "steps"), "case");
                String id = text(tc, "id", 40, true);
                if (!id.matches("[A-Za-z0-9][A-Za-z0-9._-]{0,39}") || !ids.add(id)) throw invalid(key + ": case id '" + id + "' is invalid or repeated");
                String where = key + "/" + id;
                text(tc, "name", 200, true);
                service(tc, false, where);
                var steps = tc.get("steps");
                if (steps == null || !steps.isArray() || steps.isEmpty() || steps.size() > 20) throw invalid(where + ": steps must list 1..20 steps");
                for (JsonNode step : steps) step(step, where);
            }
            result.add(c);
        }
        return result;
    }

    private static void step(JsonNode step, String where) {
        fields(step, Set.of("name", "service", "request", "expect", "capture"), "step");
        text(step, "name", 120, false);
        service(step, false, where);
        var request = step.get("request");
        fields(request, Set.of("method", "path", "headers", "json"), "request");
        String method = text(request, "method", 10, true);
        if (!METHODS.contains(method)) throw invalid(where + ": method must be one of " + METHODS);
        String path = text(request, "path", 1000, true);
        if (!path.startsWith("/") || path.startsWith("//") || path.contains("\\") || path.contains("://") || path.chars().anyMatch(ch -> ch <= ' ')) {
            throw invalid(where + ": path must be an absolute path such as /api/v1/orders");
        }
        if (request.has("headers")) {
            var headers = request.get("headers");
            if (!headers.isObject() || headers.size() > 20) throw invalid(where + ": headers must be an object of up to 20 headers");
            for (Iterator<String> it = headers.fieldNames(); it.hasNext(); ) {
                String name = it.next();
                if (!name.matches("[A-Za-z0-9-]{1,60}") || Set.of("host", "content-length", "connection", "transfer-encoding", "upgrade", "expect").contains(name.toLowerCase())) {
                    throw invalid(where + ": header '" + name + "' is not allowed");
                }
                var v = headers.get(name);
                if (!v.isTextual() || v.textValue().length() > 2000 || v.textValue().chars().anyMatch(Character::isISOControl)) throw invalid(where + ": header values must be text");
            }
        }
        var expect = step.get("expect");
        fields(expect, Set.of("status", "headers", "json", "maxMillis"), "expect");
        var status = expect.get("status");
        if (status == null || !(isStatus(status) || (status.isArray() && !status.isEmpty() && status.size() <= 10 && allStatus(status)))) {
            throw invalid(where + ": expect.status must be a status code or a list of them");
        }
        if (expect.has("maxMillis") && (!expect.get("maxMillis").isInt() || expect.get("maxMillis").intValue() < 1 || expect.get("maxMillis").intValue() > 60000)) {
            throw invalid(where + ": expect.maxMillis must be 1..60000");
        }
        if (expect.has("headers")) {
            var headers = expect.get("headers");
            if (!headers.isObject() || headers.size() > 20) throw invalid(where + ": expect.headers must be an object");
            for (JsonNode check : headers) checkSpec(check, where, false);
        }
        if (expect.has("json")) {
            var checks = expect.get("json");
            if (!checks.isArray() || checks.size() > 50) throw invalid(where + ": expect.json must be a list of up to 50 checks");
            for (JsonNode check : checks) {
                checkSpec(check, where, true);
                JsonPaths.parse(text(check, "path", 200, true));
            }
        }
        if (step.has("capture")) {
            var capture = step.get("capture");
            if (!capture.isObject() || capture.size() > 20) throw invalid(where + ": capture must be an object");
            for (Iterator<String> it = capture.fieldNames(); it.hasNext(); ) {
                String name = it.next();
                if (!name.matches("[A-Za-z][A-Za-z0-9_]{0,39}")) throw invalid(where + ": capture name '" + name + "' is invalid");
                var source = capture.get(name);
                if (!source.isTextual()) throw invalid(where + ": capture sources are text");
                String s = source.textValue();
                if (s.startsWith("header:")) { if (!s.substring(7).matches("[A-Za-z0-9-]{1,60}")) throw invalid(where + ": bad header capture"); }
                else JsonPaths.parse(s);
            }
        }
    }

    /** One header or JSON check: exactly one of exists, equals, matches, type, length (JSON checks also carry a path). */
    private static void checkSpec(JsonNode check, String where, boolean json) {
        var allowed = json ? Set.of("path", "exists", "equals", "matches", "type", "length") : Set.of("exists", "equals", "matches");
        fields(check, allowed, "check");
        int kinds = 0;
        for (String k : List.of("exists", "equals", "matches", "type", "length")) if (check.has(k)) kinds++;
        if (kinds != 1) throw invalid(where + ": each check needs exactly one of exists, equals, matches" + (json ? ", type, length" : ""));
        if (check.has("exists") && !check.get("exists").isBoolean()) throw invalid(where + ": exists must be true or false");
        if (check.has("matches")) {
            String regex = text(check, "matches", 200, true);
            try { java.util.regex.Pattern.compile(regex); } catch (Exception ex) { throw invalid(where + ": matches is not a valid regular expression"); }
        }
        if (check.has("type") && !Set.of("string", "number", "boolean", "object", "array", "null").contains(check.get("type").asText())) {
            throw invalid(where + ": type must be string, number, boolean, object, array or null");
        }
        if (check.has("length") && (!check.get("length").isInt() || check.get("length").intValue() < 0)) throw invalid(where + ": length must be a non-negative integer");
        if (!json && check.has("equals") && !check.get("equals").isTextual()) throw invalid(where + ": header equals must be text");
    }

    private static boolean isStatus(JsonNode n) { return n.isInt() && n.intValue() >= 100 && n.intValue() <= 599; }
    private static boolean allStatus(JsonNode array) { for (JsonNode n : array) if (!isStatus(n)) return false; return true; }

    private static void service(JsonNode node, boolean required, String where) {
        String s = text(node, "service", 60, required);
        if (s != null && !s.matches("[a-z0-9][a-z0-9-]{0,59}")) throw invalid(where + ": service must be a service name such as order-api");
    }

    private static void variables(JsonNode vars, String where) {
        if (vars == null) return;
        if (!vars.isObject() || vars.size() > 50) throw invalid(where + ": variables must be an object of up to 50 values");
        for (Iterator<String> it = vars.fieldNames(); it.hasNext(); ) {
            String name = it.next();
            if (!name.matches("[A-Za-z][A-Za-z0-9_]{0,39}")) throw invalid(where + ": variable name '" + name + "' is invalid");
            var v = vars.get(name);
            if (!v.isTextual() || v.textValue().length() > 500) throw invalid(where + ": variable values must be text up to 500 characters");
        }
    }

    private static void fields(JsonNode node, Set<String> allowed, String what) {
        if (node == null || !node.isObject()) throw invalid(what + " must be an object");
        for (Iterator<String> it = node.fieldNames(); it.hasNext(); ) {
            String name = it.next();
            if (!allowed.contains(name)) throw invalid("unknown " + what + " field '" + (name.length() > 40 ? name.substring(0, 40) + "…" : name) + "'");
        }
    }
    private static String text(JsonNode node, String field, int max, boolean required) {
        JsonNode v = node.get(field);
        if (v == null) { if (required) throw invalid(field + " is required"); return null; }
        if (!v.isTextual() || v.textValue().isBlank() || v.textValue().length() > max || v.textValue().chars().anyMatch(Character::isISOControl)) {
            throw invalid(field + " must be non-empty text up to " + max + " characters");
        }
        return v.textValue();
    }
    static IllegalArgumentException invalid(String reason) { return new IllegalArgumentException("invalid API test file: " + reason); }
}
